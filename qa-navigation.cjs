const {chromium}=require('playwright');
const assert=require('node:assert/strict');
(async()=>{
 const b=await chromium.launch({channel:'msedge',headless:true});
 const p=await b.newPage({viewport:{width:1440,height:1050}}),errors=[];
 p.on('pageerror',e=>errors.push(e.message));
 await p.goto('http://127.0.0.1:4173/?v=terminal#/overview');
 await p.waitForSelector('.terminal-sidebar');await p.waitForTimeout(1200);
 assert.equal(await p.locator('.side-link').count(),13);
 await p.screenshot({path:'screenshots/pro-terminal-overview.png',fullPage:true});
 await p.locator('[data-action="nav-collapse"]').click();await p.waitForTimeout(300);
 assert.equal(await p.locator('.terminal-sidebar').evaluate(e=>Math.round(e.getBoundingClientRect().width)),76);
 await p.reload();await p.waitForSelector('.terminal-sidebar');
 assert.equal(await p.locator('body').evaluate(e=>e.classList.contains('sidebar-collapsed')),true);
 await p.locator('[data-action="nav-collapse"]').click();
 await p.locator('[data-action="nav-workspaces"]').click();await p.locator('#modal a[href="#/engines"]').click();
 await p.waitForSelector('#engineScenario');
 assert.equal(await p.locator('.side-subnav button').count(),3);
 await p.locator('.side-subnav [data-action="engine-tab:planner"]').click();
 assert.match(await p.locator('main').textContent(),/Location and proposed geometry/);
 await p.setViewportSize({width:390,height:844});
 await p.locator('.mobile-menu').click();
 await p.locator('.terminal-sidebar.open').waitFor();
 await p.screenshot({path:'screenshots/pro-navigation-mobile.png'});
 await p.locator('.terminal-sidebar .side-link[href="#/overview"]').click();
 await p.waitForSelector('h1');
 assert.equal(await p.locator('.terminal-sidebar').evaluate(e=>e.classList.contains('open')),false);
 assert.equal(await p.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 await p.locator('.mobile-menu').click();await p.locator('.sidebar-shade').click({position:{x:350,y:400}});
 assert.equal(await p.locator('.terminal-sidebar').evaluate(e=>e.classList.contains('open')),false);
 assert.deepEqual(errors,[]);
 console.log('PASS: professional navigation, collapse persistence, workspace switcher, engine shortcuts, mobile drawer/backdrop and overflow.');
 await b.close();
})().catch(e=>{console.error(e);process.exit(1)});
