const {chromium}=require('playwright');
const assert=require('node:assert/strict');
(async()=>{
 const b=await chromium.launch({channel:'msedge',headless:true});
 const p=await b.newPage({viewport:{width:1600,height:1000}}),errors=[];
 p.on('pageerror',e=>errors.push(e.message));
 await p.goto('http://127.0.0.1:4173/?v=terminal-qa#/chart');
 await p.waitForSelector('.pro-chart-terminal');await p.waitForTimeout(900);
 assert.equal(await p.evaluate(()=>Math.round(document.querySelector('.chart-frame').getBoundingClientRect().height)>600),true);
 assert.equal(await p.evaluate(()=>document.documentElement.scrollHeight>innerHeight),false);
 assert.equal(await p.locator('.terminal-watch-table tbody tr[data-symbol]').count(),5);
 await p.locator('.terminal-watch-table [data-symbol="NVDA"]').click();
 assert.match(await p.locator('.terminal-symbol-button').textContent(),/NVDA/);
 await p.locator('[data-action="chart-buy"]').click();
 assert.equal(await p.locator('#orderSide').inputValue(),'Long');
 assert.equal(await p.evaluate(()=>state.positions.length),0);
 await p.locator('#orderForm button[type="submit"]').click();await p.locator('#placeOrder').click();
 await p.locator('[data-action="terminal-drawer:positions"]').first().click();
 assert.equal(await p.locator('.trading-drawer-content [data-close-position]').count(),1);
 await p.locator('[data-close-position]').click();await p.locator('#confirmAction').click();
 assert.equal(await p.evaluate(()=>state.closed.length),1);
 await p.locator('[data-chart-tab="watchlist"]').click();
 await p.locator('.study-launcher').click();await p.locator('[data-toggle-study="rsi"]').click();await p.locator('#modal [data-action="modal-close"]').click();
 assert.equal(await p.locator('.oscillator-pane').count(),1);
 await p.locator('[data-action="terminal-focus"]').click();
 assert.equal(await p.locator('.terminal-is-focused').count(),1);await p.keyboard.press('Escape');
 assert.equal(await p.locator('.terminal-is-focused').count(),0);
 await p.locator('[data-action="terminal-history"]').click();assert.equal(await p.locator('.terminal-history-label').count(),1);
 await p.locator('[data-action="terminal-history"]').click();assert.equal(await p.locator('.terminal-history-label').count(),0);
 const download=p.waitForEvent('download');await p.locator('[data-action="terminal-snapshot"]').click();assert.match((await download).suggestedFilename(),/FRYE-NVDA/);
 await p.locator('[data-action="terminal-save"]').click();assert.equal(await p.evaluate(()=>state.settings.defaultSymbol),'NVDA');
 await p.waitForTimeout(500);await p.screenshot({path:'screenshots/pro-chart-terminal.png'});
 await p.setViewportSize({width:390,height:844});await p.waitForTimeout(400);
 assert.equal(await p.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 const labels=await p.locator('.chart-frame svg text').evaluateAll(els=>els.filter(e=>Number(e.getAttribute('x'))>280).map(e=>e.getBoundingClientRect().right));
 assert.ok(labels.every(x=>x<=391),'price labels remain inside viewport');
 await p.locator('.pro-chart-toolbar [data-action="terminal-inspector"]').click();assert.equal(await p.locator('.terminal-inspector').isVisible(),true);
 await p.locator('[data-action="chart-sell"]').click();assert.equal(await p.locator('#orderSide').inputValue(),'Short');
 await p.locator('.inspector-close').click();
 await p.locator('[data-action="terminal-app-menu"]').click();await p.locator('.terminal-sidebar.open').waitFor();
 await p.locator('.side-link[href="#/overview"]').click();await p.waitForSelector('.race-hero');
 assert.equal(await p.locator('body').evaluate(e=>e.classList.contains('chart-terminal')),false);
 assert.deepEqual(errors,[]);
 console.log('PASS: viewport terminal layout, watchlist selection, buy/review/close, trading drawer, indicators, focus/Escape, history window, SVG export, save view, mobile axis labels/inspector and return to dashboard.');
 await b.close();
})().catch(e=>{console.error(e);process.exit(1)});
