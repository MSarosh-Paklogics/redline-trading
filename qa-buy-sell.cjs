const {chromium}=require('playwright');
const assert=require('node:assert/strict');
(async()=>{
 const b=await chromium.launch({channel:'msedge',headless:true});
 const p=await b.newPage({viewport:{width:1440,height:1050}}),errors=[];
 p.on('pageerror',e=>errors.push(e.message));
 await p.goto('http://127.0.0.1:4173/?v=buy-sell#/chart?symbol=NVDA&tf=1m');
 await p.waitForSelector('#quickQuantity');
 await p.locator('#quickQuantity').fill('7');await p.locator('[data-action="chart-buy"]').click();
 assert.equal(await p.locator('#orderSide').inputValue(),'Long');
 assert.equal(await p.locator('#orderSymbol').inputValue(),'NVDA');
 assert.equal(await p.locator('#orderQty').inputValue(),'7');
 assert.equal(await p.evaluate(()=>state.positions.length),0,'buy does not auto execute');
 await p.locator('#quickQuantity').fill('3');await p.locator('[data-action="chart-sell"]').click();
 assert.equal(await p.locator('#orderSide').inputValue(),'Short');
 assert.equal(await p.locator('#orderQty').inputValue(),'3');
 assert.equal(await p.evaluate(()=>state.positions.length),0,'sell does not auto execute');
 await p.locator('#orderForm button[type="submit"]').click();
 await p.locator('#placeOrder').click();
 assert.equal(await p.evaluate(()=>state.positions[0].side),'Short');
 assert.equal(await p.evaluate(()=>state.positions[0].qty),3);
 await p.setViewportSize({width:390,height:844});
 assert.equal(await p.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 await p.locator('.inspector-close').click();
 await p.locator('#quickQuantity').fill('0');await p.locator('[data-action="chart-buy"]').click();
 assert.match(await p.locator('#toast').textContent(),/whole number/);
 assert.equal(await p.evaluate(()=>state.positions.length),1,'invalid quantity cannot place another trade');
 assert.deepEqual(errors,[]);
 console.log('PASS: buy/long and sell/short tickets, symbol/quantity prefill, explicit order review, invalid quantity and mobile layout.');
 await b.close();
})().catch(e=>{console.error(e);process.exit(1)});
